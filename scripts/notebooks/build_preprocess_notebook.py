"""Generate notebooks/01b_preprocess_{1..4}.ipynb, the nnU-Net preprocessing shards (D-017).

Each notebook embeds scripts/data/preprocess_shard.py and the code it imports with
%%writefile cells and differs only in SHARD. tests/notebooks/test_notebooks.py fails if
a notebook is stale. Re-run this script after changing an embedded file.
"""

from __future__ import annotations

import json

from notebook_tools import (N_SHARDS, NNUNET_VERSION, ROOT, code_cell, md_cell, notebook,
                                   writefile_cells)

EMBEDDED = [
    "src/project3d/__init__.py",
    "src/project3d/data/__init__.py",
    "src/project3d/data/manifest.py",
    "src/project3d/data/features.py",
    "src/project3d/data/split.py",
    "src/project3d/data/nnunet_export.py",
    "scripts/data/prepare_kits23.py",
    "scripts/data/preprocess_shard.py",
]
WORKERS = 2  # Kaggle's 34 GB of RAM ran out with 3 nnU-Net workers on large scans


def path(shard: int):
    return ROOT / "notebooks" / f"01b_preprocess_{shard}.ipynb"


NOTEBOOK = path(1)

INTRO = """# SPEC 002 — nnU-Net preprocessing, shard {shard} of {n} (Kaggle, CPU only)

The preprocessed KiTS23 data is about 50 GB, but one notebook can save only about
20 GB. So {n} notebooks each preprocess a quarter of the cases, following the shard
plan written by `kits23-prepare-data` (D-017). Each case runs in its own process,
{workers} at a time; a case that crashes is retried alone. **No GPU quota.**

**Before running**
1. *Add Input*: the outputs of `kits23-stage-1..3` and `kits23-prepare-data`.
2. *Settings*: **Accelerator = None**, **Internet = On**, keep it **Private**.
3. **Save Version → Save & Run All (Commit)**. Expected: about 2 hours.

The training notebook (SPEC 003) attaches all {n} shard outputs.

Generated by `scripts/notebooks/build_preprocess_notebook.py`; edit the repository, not this notebook."""

SETUP = f"""import os, sys, subprocess
for sub in ("src/project3d/data", "scripts/data"):
    os.makedirs(f"/kaggle/working/project23d/{{sub}}", exist_ok=True)
subprocess.run([sys.executable, "-m", "pip", "install", "-q", "nnunetv2=={NNUNET_VERSION}", "nibabel"],
               check=True)"""

RUN = """SHARD = {shard}
W = "/kaggle/working/project23d"
os.environ["PYTHONPATH"] = f"{{W}}/src"
os.environ.update({{k: "/tmp/" + k for k in ("nnUNet_raw", "nnUNet_preprocessed", "nnUNet_results")}})
code = subprocess.run([sys.executable, f"{{W}}/scripts/data/preprocess_shard.py",
                       "--input-root", "/kaggle/input", "--shard", str(SHARD), "--workers", "{workers}",
                       "--out-dir", "/kaggle/working/nnUNet_preprocessed/Dataset220_KiTS2023/nnUNetPlans_3d_fullres",
                       "--record", f"/kaggle/working/spec002/shard_{{SHARD}}.json"]).returncode
print("DONE" if code == 0 else "SOME CASES FAILED: see the record above.",
      "Copy the printed record back to Claude.")"""


def build(shard: int = 1) -> dict:
    return notebook([md_cell(INTRO.format(shard=shard, n=N_SHARDS, workers=WORKERS)), code_cell(SETUP),
                     *writefile_cells(EMBEDDED), code_cell(RUN.format(shard=shard, workers=WORKERS))])


def render(shard: int = 1) -> str:
    return json.dumps(build(shard), indent=1, ensure_ascii=False) + "\n"


if __name__ == "__main__":
    for k in range(1, N_SHARDS + 1):
        path(k).parent.mkdir(parents=True, exist_ok=True)
        path(k).write_text(render(k), encoding="utf-8", newline="\n")
        print(f"wrote {path(k)}")

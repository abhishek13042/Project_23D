"""Generate notebooks/03_evaluate.ipynb (SPEC 004 + SPEC 005) from the tested sources.

Same approach as scripts/notebooks/build_prepare_notebook.py: the notebook embeds the
repository code with %%writefile cells, and tests/notebooks/test_notebooks.py fails if
the notebook is stale. Re-run this script after changing an embedded file.
"""

from __future__ import annotations

from pathlib import Path

from notebook_tools import NNUNET_VERSION, ROOT, code_cell, md_cell, notebook, writefile_cells

NOTEBOOK = ROOT / "notebooks" / "03_evaluate.ipynb"
EMBEDDED = [
    "src/project3d/__init__.py",
    "src/project3d/data/__init__.py",
    "src/project3d/data/manifest.py",
    "src/project3d/data/features.py",
    "src/project3d/data/split.py",
    "src/project3d/data/nnunet_export.py",
    "src/project3d/eval/__init__.py",
    "src/project3d/eval/metrics.py",
    "src/project3d/eval/stats.py",
    "src/project3d/eval/official.py",
    "src/project3d/eval/analysis.py",
    "src/project3d/eval/figures.py",
    "scripts/data/prepare_kits23.py",
    "scripts/eval/evaluate.py",
    "scripts/eval/case_analysis.py",
]
KITS23_PIP = "git+https://github.com/neheller/kits23"
N_CASES = 489  # full KiTS23 v0.1.4; smaller folders (validation outputs) are ignored

INTRO = """# SPEC 004 + 005 — Test-set inference, evaluation and case analysis (Kaggle GPU)

Runs the trained nnU-Net model (SPEC 003, fold 0) **once** on the 73 locked test
cases, scores them with the official KiTS23 evaluator, and writes the case
analysis and figures.

**Before running**
1. *Add Input*: the outputs of `kits23-stage-1..3` (KiTS23 images and segmentations), `kits23-prepare-data`
   (from SPEC 002, it holds `spec002/split.json`), and the training output dataset
   (the folder that holds `fold_0/checkpoint_final.pth`).
2. *Settings*: **Accelerator = GPU T4 x1** (or P100), **Internet = On**.
3. **Save Version → Save & Run All (Commit)**. Expected GPU time: about 7-8 hours, from
   the 5.6 min per case measured in SPEC 003's validation (`DISABLE_TTA = True` in
   step 3 is about 8x faster, usually with slightly lower Dice).

**Rules this notebook follows** (docs/evaluation.md, D-012):
- post-processing is chosen on the *validation* predictions only, then applied to test;
- test results are computed once; nothing is tuned on them afterwards;
- post-processed predictions are the primary result, raw ones are reported too.

The code cells are generated by `scripts/notebooks/build_eval_notebook.py`.
Edit the repository, not this notebook."""

ENV_CHECK = f"""# Step 0 - machine check and folders
import os, shutil, sys, platform, json, time, subprocess
from pathlib import Path
print("python", sys.version.split()[0], "|", platform.platform(), "| CPUs:", os.cpu_count())
subprocess.run(["nvidia-smi", "--query-gpu=name,memory.total", "--format=csv"])
WORK = "/kaggle/working/project23d"
for sub in {sorted({str(Path(p).parent).replace(chr(92), "/") for p in EMBEDDED})!r}:
    os.makedirs(f"{{WORK}}/{{sub}}", exist_ok=True)
T0 = time.time()"""

INSTALL = f"""# Step 1 - install nnU-Net (same pinned version as training) and the official evaluator
import importlib.metadata as md
def sh(cmd):
    cmd = [str(c) for c in cmd]
    print("$", " ".join(cmd), flush=True)
    subprocess.run(cmd, check=True)
sh([sys.executable, "-m", "pip", "install", "-q", "nnunetv2=={NNUNET_VERSION}", "nibabel",
    "{KITS23_PIP}"])
print("nnunetv2", md.version("nnunetv2"), "| torch", md.version("torch"), "| kits23", md.version("kits23"))"""

LOCATE = f"""# Step 2 - find the inputs: KiTS23 folders, trained model, locked split
sys.path[:0] = [f"{{WORK}}/src", f"{{WORK}}/scripts/data", f"{{WORK}}/scripts/eval"]
import prepare_kits23
from project3d.data import manifest
INPUT = Path("/kaggle/input")
IMAGES, SEGS = prepare_kits23.detect_roots(INPUT, min_files={N_CASES}, link_dir=Path("/tmp/kits23_merged"))
ckpts = sorted(INPUT.rglob("fold_0/checkpoint_final.pth"))
assert len(ckpts) == 1, f"need exactly one fold_0/checkpoint_final.pth, found {{ckpts}}"
FOLD = ckpts[0].parent
TRAINER = FOLD.parent  # e.g. .../nnUNetTrainer_100epochs__nnUNetPlans__3d_fullres
for name in ("plans.json", "dataset.json"):
    assert (TRAINER / name).exists(), f"missing {{TRAINER / name}}"
splits = [p for p in INPUT.rglob("split.json") if "roles" in json.loads(p.read_text())]
assert len(splits) == 1, f"need exactly one SPEC 002 split.json, found {{splits}}"
SPLIT = splits[0]
FEATURES = SPLIT.parent / "case_features.csv"
assert FEATURES.exists(), FEATURES
split_record = json.loads(SPLIT.read_text())
roles = split_record["roles"]
TEST = sorted(c for c, r in roles.items() if r == "test")
VAL = sorted(c for c, r in roles.items() if r == "val")
print("images:", IMAGES, "| segmentations:", SEGS)
print("model:", TRAINER)
print("split:", SPLIT, "| fingerprint", split_record["fingerprint_sha256"][:16], "...")
print(f"{{len(TEST)}} test cases, {{len(VAL)}} validation cases")
for var in ("nnUNet_raw", "nnUNet_preprocessed", "nnUNet_results"):  # silences nnU-Net warnings
    os.environ.setdefault(var, f"/tmp/{{var}}")
OUT = Path("/kaggle/working/spec004")
OUT.mkdir(parents=True, exist_ok=True)"""

PREDICT = """# Step 3 - predict the test cases (GPU). Test images are linked with nnU-Net's
# _0000 channel suffix; nothing is copied.
DISABLE_TTA = False  # True: about 8x faster, usually slightly lower Dice
images = manifest.find_case_files(IMAGES)
IMGS_TS = Path("/tmp/imagesTs")
IMGS_TS.mkdir(exist_ok=True)
for c in TEST:
    src = images[c][0]
    assert src.name.endswith(".nii.gz"), src
    dst = IMGS_TS / f"{c}_0000.nii.gz"
    if not dst.exists():
        dst.symlink_to(src)
t = time.time()
cmd = ["nnUNetv2_predict_from_modelfolder", "-i", IMGS_TS, "-o", OUT / "pred_raw",
       "-m", TRAINER, "-f", "0", "-chk", "checkpoint_final.pth",
       "-npp", "1", "-nps", "2"]  # few workers: Kaggle's RAM ran out with 3 in SPEC 002
if DISABLE_TTA:
    cmd.append("--disable_tta")
sh(cmd)
predict_hours = (time.time() - t) / 3600
print(f"prediction took {predict_hours:.2f} h")"""

POSTPROCESS = """# Step 4 - choose post-processing on the VALIDATION predictions only, apply it to test.
# nnU-Net writes postprocessing.pkl next to its input, so the validation folder is
# copied somewhere writable first.
VAL_SRC = FOLD / "validation"
val_found = sorted(p.name[:-7] for p in VAL_SRC.glob("case_*.nii.gz")) if VAL_SRC.is_dir() else []
pp_applied = val_found == VAL
if pp_applied:
    VAL_PRED, VAL_REF = Path("/tmp/val_pred"), Path("/tmp/val_ref")
    shutil.copytree(VAL_SRC, VAL_PRED, dirs_exist_ok=True)
    VAL_REF.mkdir(exist_ok=True)
    segs = manifest.find_case_files(SEGS)
    for c in VAL:
        if not (VAL_REF / f"{c}.nii.gz").exists():
            (VAL_REF / f"{c}.nii.gz").symlink_to(segs[c][0])
    common = ["-plans_json", TRAINER / "plans.json", "-dataset_json", TRAINER / "dataset.json", "-np", "4"]
    sh(["nnUNetv2_determine_postprocessing", "-i", VAL_PRED, "-ref", VAL_REF, *common])
    PKL = VAL_PRED / "postprocessing.pkl"
    sh(["nnUNetv2_apply_postprocessing", "-i", OUT / "pred_raw", "-o", OUT / "pred_pp",
        "-pp_pkl_file", PKL, *common])
    shutil.copy(PKL, OUT / "postprocessing.pkl")
    import pickle
    print("post-processing chosen on validation:", pickle.load(open(PKL, "rb")))
else:
    print(f"fold_0/validation has {len(val_found)} of {len(VAL)} expected cases: "
          "post-processing SKIPPED, the primary result uses the raw predictions.")
    shutil.copytree(OUT / "pred_raw", OUT / "pred_pp", dirs_exist_ok=True)"""

EVALUATE = """# Step 5 - score both prediction sets with the official KiTS23 evaluator (CPU).
# evaluate.py stops if a prediction is missing or misaligned, or if our Dice and
# the official Dice disagree (a sign of an orientation bug).
for tag in ("pp", "raw"):
    sh([sys.executable, f"{WORK}/scripts/eval/evaluate.py", "--pred-dir", OUT / f"pred_{tag}",
        "--segs-root", SEGS, "--split", SPLIT, "--role", "test",
        "--out-dir", OUT / f"eval_{tag}", "--np", "4"])"""

ANALYSE = """# Step 6 - SPEC 005: performance by case characteristics, figures
sh([sys.executable, f"{WORK}/scripts/eval/case_analysis.py",
    "--per-case", OUT / "eval_pp" / "per_case.csv", "--case-features", FEATURES,
    "--images-root", IMAGES, "--segs-root", SEGS, "--pred-dir", OUT / "pred_pp",
    "--out-dir", OUT / "analysis"])
from IPython.display import Image, Markdown, display
display(Markdown((OUT / "analysis" / "analysis.md").read_text()))
for png in sorted((OUT / "analysis" / "figures").glob("*.png")):
    display(Image(str(png)))"""

RECORD = """# Step 7 - run record (copy the printed JSON back to Claude)
import hashlib, torch
def primary(tag):
    s = json.loads((OUT / f"eval_{tag}" / "summary.json").read_text())
    return {k: {"mean": v.get("mean"), "ci95": v.get("ci95")} for k, v in s["primary"].items()}, s
pp, summary = primary("pp")
raw, _ = primary("raw")
ckpt = FOLD / "checkpoint_final.pth"
record = {
    "spec": "SPEC 004", "nnunetv2": md.version("nnunetv2"), "torch": md.version("torch"),
    "kits23_evaluator": summary.get("kits23_evaluator"),
    "gpu": torch.cuda.get_device_name(0) if torch.cuda.is_available() else None,
    "trainer_dir": TRAINER.name, "checkpoint_mb": round(ckpt.stat().st_size / 1e6, 1),
    "split_fingerprint_sha256": split_record["fingerprint_sha256"],
    "n_test_cases": summary["n_cases"], "disable_tta": DISABLE_TTA,
    "postprocessing_applied": pp_applied,
    "dice_crosscheck_max_abs_diff": summary.get("dice_crosscheck_max_abs_diff"),
    "primary_postprocessed": pp, "primary_raw": raw,
    "predict_hours": round(predict_hours, 2), "total_hours": round((time.time() - T0) / 3600, 2),
}
json.dump(record, open(OUT / "run_record.json", "w"), indent=2)
print(json.dumps(record, indent=1))
print("DONE. Save the Output as a private dataset (e.g. kits23-spec004-results).")"""


def build() -> dict:
    return notebook([md_cell(INTRO), code_cell(ENV_CHECK), *writefile_cells(EMBEDDED),
                     code_cell(INSTALL), code_cell(LOCATE), code_cell(PREDICT),
                     code_cell(POSTPROCESS), code_cell(EVALUATE), code_cell(ANALYSE),
                     code_cell(RECORD)])


def render() -> str:
    import json

    return json.dumps(build(), indent=1, ensure_ascii=False) + "\n"


if __name__ == "__main__":
    NOTEBOOK.parent.mkdir(parents=True, exist_ok=True)
    NOTEBOOK.write_text(render(), encoding="utf-8", newline="\n")
    print(f"wrote {NOTEBOOK}")

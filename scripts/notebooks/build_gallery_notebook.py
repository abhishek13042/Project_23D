"""Generate notebooks/04_gallery.ipynb (SPEC 009) from the tested sources.

Same approach as build_eval_notebook.py: the notebook embeds the repository code with
%%writefile cells, and tests/notebooks/test_notebooks.py fails if the notebook is stale.
"""

from __future__ import annotations

from pathlib import Path

from notebook_tools import ROOT, code_cell, md_cell, notebook, writefile_cells

NOTEBOOK = ROOT / "notebooks" / "04_gallery.ipynb"
EMBEDDED = [
    "src/project3d/__init__.py",
    "src/project3d/data/__init__.py",
    "src/project3d/data/manifest.py",
    "src/project3d/data/features.py",
    "src/project3d/data/split.py",
    "src/project3d/data/nnunet_export.py",
    "src/project3d/eval/__init__.py",
    "src/project3d/eval/metrics.py",
    "scripts/data/prepare_kits23.py",
    "scripts/gallery/select_cases.py",
    "scripts/gallery/build_gallery.py",
]
N_CASES = 489

INTRO = """# SPEC 009 — Build the demo gallery (Kaggle CPU)

Chooses the gallery cases by a fixed rule and crops them. It uses the evaluated predictions from
`kits23-evaluate`, so nothing is predicted again and no GPU is needed.

**Before running**
1. *Add Input*: the outputs of `kits23-stage-1..3`, `kits23-prepare-data` and `kits23-evaluate`.
2. **Save Version → Save & Run All (Commit)**. Expected time: a few minutes.

The output folder `gallery/` is what goes to Hugging Face as a dataset.

The code cells are generated by `scripts/notebooks/build_gallery_notebook.py`.
Edit the repository, not this notebook."""

ENV_CHECK = f"""# Step 0 - folders and packages
import json, os, subprocess, sys
from pathlib import Path
WORK = "/kaggle/working/project23d"
for sub in {sorted({str(Path(p).parent).replace(chr(92), "/") for p in EMBEDDED})!r}:
    os.makedirs(f"{{WORK}}/{{sub}}", exist_ok=True)
def sh(cmd):
    cmd = [str(c) for c in cmd]
    print("$", " ".join(cmd), flush=True)
    subprocess.run(cmd, check=True)
sh([sys.executable, "-m", "pip", "install", "-q", "nibabel"])"""

LOCATE = f"""# Step 1 - find the inputs
sys.path[:0] = [f"{{WORK}}/src", f"{{WORK}}/scripts/data"]
import prepare_kits23
INPUT = Path("/kaggle/input")
IMAGES, SEGS = prepare_kits23.detect_roots(INPUT, min_files={N_CASES}, link_dir=Path("/tmp/kits23_merged"))
per_case = sorted(INPUT.rglob("spec004/eval_pp/per_case.csv"))
assert len(per_case) == 1, per_case
SPEC004 = per_case[0].parent.parent
features = sorted(INPUT.rglob("case_features.csv"))
assert len(features) >= 1, "SPEC 002 case_features.csv not found"
OUT = Path("/kaggle/working/gallery")
OUT.mkdir(parents=True, exist_ok=True)"""

BUILD = """# Step 2 - select and package
CASES = Path("/kaggle/working/gallery_cases.json")
sh([sys.executable, f"{WORK}/scripts/gallery/select_cases.py", "--per-case", per_case[0],
    "--case-features", features[0], "--out", CASES])
sh([sys.executable, f"{WORK}/scripts/gallery/build_gallery.py", "--cases", CASES, "--per-case", per_case[0],
    "--images-root", IMAGES, "--segs-root", SEGS, "--pred-dir", SPEC004 / "pred_pp", "--out-dir", OUT])
print((OUT / "index.json").read_text())"""


def build() -> dict:
    return notebook([md_cell(INTRO), code_cell(ENV_CHECK), *writefile_cells(EMBEDDED), code_cell(LOCATE),
                     code_cell(BUILD)])


def render() -> str:
    import json

    return json.dumps(build(), indent=1, ensure_ascii=False) + "\n"


if __name__ == "__main__":
    NOTEBOOK.parent.mkdir(parents=True, exist_ok=True)
    NOTEBOOK.write_text(render(), encoding="utf-8", newline="\n")
    print(f"wrote {NOTEBOOK}")

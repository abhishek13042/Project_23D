"""Generate notebooks/03b_release_model.ipynb (SPEC 008) from the tested sources.

Same approach as build_eval_notebook.py: the notebook embeds the repository code with
%%writefile cells, and tests/notebooks/test_notebooks.py fails if the notebook is stale.
"""

from __future__ import annotations

from pathlib import Path

from notebook_tools import NNUNET_VERSION, ROOT, code_cell, md_cell, notebook, writefile_cells

NOTEBOOK = ROOT / "notebooks" / "03b_release_model.ipynb"
EMBEDDED = [
    "src/project3d/__init__.py",
    "src/project3d/data/__init__.py",
    "src/project3d/data/manifest.py",
    "src/project3d/data/features.py",
    "src/project3d/data/split.py",
    "src/project3d/data/nnunet_export.py",
    "src/project3d/eval/__init__.py",
    "src/project3d/eval/metrics.py",
    "src/project3d/eval/stats.py",
    "src/project3d/eval/official.py",
    "src/project3d/eval/postprocess.py",
    "src/project3d/inference/__init__.py",
    "src/project3d/inference/predictor.py",
    "src/project3d/training/nnunet_trainer.py",
    "scripts/data/prepare_kits23.py",
    "scripts/eval/evaluate.py",
    "scripts/inference/benchmark.py",
    "scripts/release/export_model.py",
    "reports/release/model_card.md",
]
KITS23_PIP = "git+https://github.com/neheller/kits23"
N_CASES = 489

INTRO = """# SPEC 008 — Package the model and measure the inference settings (Kaggle GPU)

Packages the trained model with checksums, then measures three inference settings on validation
cases. **The test set is not touched** (D-014).

**Before running**
1. *Add Input*: the outputs of `kits23-stage-1..3`, `kits23-prepare-data` and `kits23-train-2`.
2. *Settings*: **Accelerator = GPU T4 x1**, **Internet = On**.
3. **Save Version → Save & Run All (Commit)**. Expected GPU time: about 40 minutes.

The code cells are generated by `scripts/notebooks/build_release_notebook.py`.
Edit the repository, not this notebook."""

ENV_CHECK = f"""# Step 0 - machine check and folders
import json, os, shutil, subprocess, sys, time
from pathlib import Path
subprocess.run(["nvidia-smi", "--query-gpu=name,memory.total", "--format=csv"])
WORK = "/kaggle/working/project23d"
for sub in {sorted({str(Path(p).parent).replace(chr(92), "/") for p in EMBEDDED})!r}:
    os.makedirs(f"{{WORK}}/{{sub}}", exist_ok=True)
T0 = time.time()"""

INSTALL = f"""# Step 1 - install nnU-Net (same pinned version as training) and the official evaluator
def sh(cmd):
    cmd = [str(c) for c in cmd]
    print("$", " ".join(cmd), flush=True)
    subprocess.run(cmd, check=True)
sh([sys.executable, "-m", "pip", "install", "-q", "nnunetv2=={NNUNET_VERSION}", "nibabel",
    "{KITS23_PIP}"])
for var in ("nnUNet_raw", "nnUNet_preprocessed", "nnUNet_results"):  # silences nnU-Net warnings
    os.environ.setdefault(var, f"/tmp/{{var}}")"""

LOCATE = f"""# Step 2 - find the inputs: KiTS23 folders, trained model, locked split
sys.path[:0] = [f"{{WORK}}/src", f"{{WORK}}/scripts/data"]
import prepare_kits23
INPUT = Path("/kaggle/input")
IMAGES, SEGS = prepare_kits23.detect_roots(INPUT, min_files={N_CASES}, link_dir=Path("/tmp/kits23_merged"))
ckpts = sorted(INPUT.rglob("fold_0/checkpoint_final.pth"))
assert len(ckpts) == 1, f"need exactly one fold_0/checkpoint_final.pth, found {{ckpts}}"
FOLD = ckpts[0].parent
splits = [p for p in INPUT.rglob("split.json") if "roles" in json.loads(p.read_text())]
assert len(splits) == 1, f"need exactly one SPEC 002 split.json, found {{splits}}"
OUT = Path("/kaggle/working/spec008")
OUT.mkdir(parents=True, exist_ok=True)
PACKAGE = Path("/kaggle/working/model_package")"""

PACKAGE = """# Step 3 - package the model and verify the checksums
sh([sys.executable, f"{WORK}/scripts/release/export_model.py", "--trainer-dir", FOLD.parent, "--out-dir", PACKAGE])
sys.path.insert(0, f"{WORK}/scripts/release")
import export_model
assert export_model.verify(PACKAGE) == [], "checksum mismatch"
shutil.copy(PACKAGE / "checksums.json", OUT / "model_checksums.json")"""

BENCHMARK = """# Step 4 - three settings on validation cases. The default setting is also compared with
# the prediction saved in SPEC 003's validation, which proves this predictor matches evaluation.
sh([sys.executable, f"{WORK}/scripts/inference/benchmark.py", "--model-dir", PACKAGE, "--images-root", IMAGES,
    "--segs-root", SEGS, "--split", splits[0], "--training-validation", FOLD / "validation",
    "--out", OUT / "inference_benchmark.json"])
print(f"DONE in {(time.time() - T0) / 3600:.2f} h")"""


def build() -> dict:
    return notebook([md_cell(INTRO), code_cell(ENV_CHECK), *writefile_cells(EMBEDDED), code_cell(INSTALL),
                     code_cell(LOCATE), code_cell(PACKAGE), code_cell(BENCHMARK)])


def render() -> str:
    import json

    return json.dumps(build(), indent=1, ensure_ascii=False) + "\n"


if __name__ == "__main__":
    NOTEBOOK.parent.mkdir(parents=True, exist_ok=True)
    NOTEBOOK.write_text(render(), encoding="utf-8", newline="\n")
    print(f"wrote {NOTEBOOK}")

"""Generate notebooks/05_run_on_your_scan.ipynb (SPEC 010, fallback B) from the tested sources.

Visitors open this on their own free Kaggle or Colab account. It uses the same predictor as the
Space, so results match the live demo's post-processing.
"""

from __future__ import annotations

from pathlib import Path

from notebook_tools import NNUNET_VERSION, ROOT, code_cell, md_cell, notebook, writefile_cells

NOTEBOOK = ROOT / "notebooks" / "05_run_on_your_scan.ipynb"
EMBEDDED = [
    "src/project3d/__init__.py",
    "src/project3d/data/__init__.py",
    "src/project3d/data/features.py",
    "src/project3d/eval/__init__.py",
    "src/project3d/eval/postprocess.py",
    "src/project3d/inference/__init__.py",
    "src/project3d/inference/predictor.py",
]

INTRO = """# Run the kidney segmentation model on your own scan

> **Research demo, not for clinical use.** Use anonymized scans only. The model makes real errors,
> and it is weakest on small tumors and on cysts.

This notebook runs on your own free Kaggle or Colab GPU, so your scan stays in your session.

1. Turn on a **GPU** and **Internet** in the notebook settings.
2. Add your `.nii` or `.nii.gz` CT scan. On Kaggle, use *Add Input*. On Colab, upload it to the
   Files panel. If you set no path below, the notebook uses the first scan it finds.
3. Run all the cells. It takes about 8 minutes per scan on a Kaggle GPU, plus a few minutes of setup.

The weights are derived from KiTS23 and are licensed CC BY-NC-SA 4.0: non-commercial use only.

The code cells are generated by `scripts/notebooks/build_run_notebook.py`.
Edit the repository, not this notebook."""

SETTINGS = """# Step 0 - settings
MODEL_REPO = ""  # the Hugging Face model repository, for example "your-name/kits23-nnunet"
SCAN = ""        # path to your scan; leave empty to use the first one found"""

ENV_CHECK = f"""# Step 1 - folders and packages
import os, subprocess, sys
from pathlib import Path
WORK = "/kaggle/working/project23d"
for sub in {sorted({str(Path(p).parent).replace(chr(92), "/") for p in EMBEDDED})!r}:
    os.makedirs(f"{{WORK}}/{{sub}}", exist_ok=True)
subprocess.run([sys.executable, "-m", "pip", "install", "-q", "nnunetv2=={NNUNET_VERSION}", "nibabel"], check=True)
for var in ("nnUNet_raw", "nnUNet_preprocessed", "nnUNet_results"):  # silences nnU-Net warnings
    os.environ.setdefault(var, f"/tmp/{{var}}")"""

FIND = """# Step 2 - find the model and the scan
import torch
from huggingface_hub import snapshot_download
sys.path.insert(0, f"{WORK}/src")
ROOTS = [Path("/kaggle/input"), Path("/content")]
def search(pattern):
    return [p for root in ROOTS if root.exists() for p in sorted(root.rglob(pattern))]
packaged = search("checksums.json")
MODEL_DIR = packaged[0].parent if packaged else snapshot_download(MODEL_REPO)
scans = [p for suffix in ("*.nii.gz", "*.nii") for p in search(suffix)
         if p.name not in ("pred.nii.gz", "gt.nii.gz")]
assert SCAN or scans, "No scan found. Add a .nii or .nii.gz file, or set SCAN above."
SCAN = Path(SCAN or scans[0])
DEVICE = "cuda" if torch.cuda.is_available() else "cpu"
print("scan:", SCAN.name, "| device:", DEVICE)"""

RUN = """# Step 3 - segment. Test-time augmentation stays on, as in the evaluation.
from project3d.inference.predictor import NnUNetModel, Options, Predictor
OPTIONS = Options(tta=True, device=DEVICE)
OUT = Path("segmentation.nii.gz").resolve()
summary = Predictor(NnUNetModel(MODEL_DIR, OPTIONS), OPTIONS).predict_file(SCAN, OUT)
print(summary["volumes_ml"])
print("Saved", OUT, "- labels: 1 kidney, 2 tumor, 3 cyst")"""

SHOW = """# Step 4 - look at the slice with the most foreground. Research demo, not for clinical use.
import matplotlib.pyplot as plt
import nibabel as nib
import numpy as np
ct = np.asanyarray(nib.load(str(SCAN)).dataobj)
seg = np.asanyarray(nib.load(str(OUT)).dataobj)
axis = int(np.argmin(seg.shape))
others = tuple(i for i in range(3) if i != axis)
index = int((seg > 0).sum(axis=others).argmax())
plt.figure(figsize=(6, 6))
plt.imshow(np.take(ct, index, axis).T, cmap="gray", vmin=-200, vmax=300, origin="lower")
plt.imshow(np.ma.masked_equal(np.take(seg, index, axis).T, 0), cmap="autumn", alpha=0.45, origin="lower")
plt.title(f"Slice {index}. Research demo, not for clinical use")
plt.axis("off")
plt.savefig("overlay.png", dpi=120, bbox_inches="tight")
plt.show()"""


def build() -> dict:
    return notebook([md_cell(INTRO), code_cell(SETTINGS), code_cell(ENV_CHECK), *writefile_cells(EMBEDDED),
                     code_cell(FIND), code_cell(RUN), code_cell(SHOW)])


def render() -> str:
    import json

    return json.dumps(build(), indent=1, ensure_ascii=False) + "\n"


if __name__ == "__main__":
    NOTEBOOK.parent.mkdir(parents=True, exist_ok=True)
    NOTEBOOK.write_text(render(), encoding="utf-8", newline="\n")
    print(f"wrote {NOTEBOOK}")

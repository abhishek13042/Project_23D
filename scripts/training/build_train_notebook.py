"""Generate the SPEC 003 training notebooks from the tested sources.

- notebooks/02_train_pilot.ipynb: nnU-Net's own 5-epoch trainer. It is a short GPU
  run that checks the whole pipeline and measures the time per epoch.
- notebooks/02_train.ipynb: the real 100-epoch run (D-016). One Kaggle session
  can't fit it, so the same notebook is pushed as kits23-train-1, -2, ...; each
  later session attaches the previous session's output and resumes from it.

Same approach as scripts/data/build_kaggle_notebook.py: tests/data/test_notebook.py
fails if a notebook is stale. Re-run this script after changing an embedded file.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "data"))

from build_kaggle_notebook import NNUNET_VERSION, ROOT, code_cell, md_cell, notebook, writefile_cells  # noqa: E402

EMBEDDED = [
    "src/project3d/training/nnunet_trainer.py",
    "scripts/training/train.py",
]
SESSION_HOURS = 12  # Kaggle's limit for one GPU session
RUNS = {
    "pilot": {"trainer": "nnUNetTrainer_5epochs", "budget_hours": 1.5,
              "path": ROOT / "notebooks" / "02_train_pilot.ipynb"},
    "full": {"trainer": "nnUNetTrainer_100epochs_kaggle", "budget_hours": 11.25,
             "path": ROOT / "notebooks" / "02_train.ipynb"},
}
NOTEBOOK = RUNS["full"]["path"]

INTRO = {
    "pilot": """# SPEC 003 pilot — 5 nnU-Net epochs on Kaggle (GPU T4)

A short GPU run before the long one. It checks that the preprocessed data loads,
the GPU works and nnU-Net finishes and validates. It also measures **seconds per
epoch**, and that number decides how many sessions the 100-epoch run needs.

**Before running**
1. *Add Input*: the output of `kits23-prepare-data` (SPEC 002).
2. *Settings*: **Accelerator = GPU T4 x1**, **Internet = On**.
3. **Save Version → Save & Run All (Commit)**. Expected GPU time: about 1-1.5 hours,
   most of it for nnU-Net's validation of the 73 validation cases.""",
    "full": f"""# SPEC 003 — Train nnU-Net 3d_fullres, fold 0, 100 epochs (Kaggle GPU T4)

100 epochs don't fit in one {SESSION_HOURS}-hour Kaggle session, so this notebook
runs in **sessions**. Each session trains until its time budget runs out and keeps
a checkpoint every 5 epochs (D-016). The next session picks up from that checkpoint.

**Before running**
1. *Add Input*: the output of `kits23-prepare-data` (SPEC 002). **Sessions 2, 3, ...**
   also attach the output of the *previous* training session (only that one).
2. *Settings*: **Accelerator = GPU T4 x1**, **Internet = On**.
3. **Save Version → Save & Run All (Commit)**.

**At the end** the last cell prints one of these:
- `NOT FINISHED`: push the next session with this output attached;
- `DONE`: `fold_0/checkpoint_final.pth` and the fold-0 validation are in the output.
  The evaluation notebook (SPEC 004) uses that output;
- `STOP`: nnU-Net crashed. Read the log above it.""",
}
NOTE = """
The code cells are generated by `scripts/training/build_train_notebook.py`.
Edit the repository, not this notebook."""

ENV_CHECK = """# Step 0 - machine check
import os, shutil, sys, platform, json, time, subprocess
from pathlib import Path
T0 = time.time()
print("python", sys.version.split()[0], "|", platform.platform(), "| CPUs:", os.cpu_count())
subprocess.run(["nvidia-smi", "--query-gpu=name,memory.total", "--format=csv"])
for d in ("/kaggle/working", "/tmp"):
    u = shutil.disk_usage(d)
    print(f"{d}: {u.free / 1e9:.0f} GB free")
WORK = "/kaggle/working/project23d"
for sub in ("src/project3d/training", "scripts/training"):
    os.makedirs(f"{WORK}/{sub}", exist_ok=True)"""

INSTALL = f"""# Step 1 - install nnU-Net (same pinned version as SPEC 002) and register our
# trainer: nnU-Net only finds trainers inside its own package folder.
import importlib.metadata as md
def sh(cmd):
    cmd = [str(c) for c in cmd]
    print("$", " ".join(cmd), flush=True)
    subprocess.run(cmd, check=True)
sh([sys.executable, "-m", "pip", "install", "-q", "nnunetv2=={NNUNET_VERSION}"])
import nnunetv2, torch
variants = Path(nnunetv2.__file__).parent / "training" / "nnUNetTrainer" / "variants"
shutil.copy(f"{{WORK}}/src/project3d/training/nnunet_trainer.py", variants / "project23d_trainer.py")
GPU = torch.cuda.get_device_name(0) if torch.cuda.is_available() else "none"
assert GPU != "none", "no GPU: set Accelerator = GPU T4 x1"
print("nnunetv2", md.version("nnunetv2"), "| torch", md.version("torch"), "|", GPU)"""

TRAIN = """# Step 2 - train until done or until the session's time budget runs out.
# Data augmentation runs on the 4 CPUs; torch.compile is off (D-016).
os.environ.update({{
    "nnUNet_raw": "/tmp/nnUNet_raw",
    "nnUNet_preprocessed": "/tmp/nnUNet_preprocessed",
    "nnUNet_results": "/kaggle/working/nnUNet_results",
    "nnUNet_n_proc_DA": "4",
    "nnUNet_compile": "f",
}})
TRAINER = "{trainer}"
budget = {budget_hours} - (time.time() - T0) / 3600
sh([sys.executable, f"{{WORK}}/scripts/training/train.py",
    "--input-root", "/kaggle/input",
    "--preprocessed-root", os.environ["nnUNet_preprocessed"],
    "--results-root", os.environ["nnUNet_results"],
    "--trainer", TRAINER, "--budget-hours", f"{{budget:.3f}}", "--gpu", GPU,
    "--out", "/kaggle/working/spec003/run_record.json"])
print("Copy the printed run record above back to Claude.")"""


def build(run: str = "full") -> dict:
    cfg = RUNS[run]
    return notebook([md_cell(INTRO[run] + "\n" + NOTE), code_cell(ENV_CHECK), *writefile_cells(EMBEDDED),
                     code_cell(INSTALL), code_cell(TRAIN.format(**cfg))])


def render(run: str = "full") -> str:
    return json.dumps(build(run), indent=1, ensure_ascii=False) + "\n"


if __name__ == "__main__":
    for run, cfg in RUNS.items():
        cfg["path"].parent.mkdir(parents=True, exist_ok=True)
        cfg["path"].write_text(render(run), encoding="utf-8", newline="\n")
        print(f"wrote {cfg['path']}")

"""Generate notebooks/00_stage_data_{1,2,3}.ipynb, the KiTS23 download shards (D-015).

Each notebook embeds scripts/data/stage_kits23.py and the checksum manifest with
%%writefile cells and differs only in SHARD. tests/data/test_notebook.py fails if
a notebook is stale. Re-run this script after changing an embedded file.
"""

from __future__ import annotations

import json

from build_kaggle_notebook import ROOT, code_cell, md_cell, notebook, writefile_cells

N_SHARDS = 3
EMBEDDED = ["scripts/data/stage_kits23.py", "data/sources/kits23_v0.1.4_files.tsv"]


def path(shard: int):
    return ROOT / "notebooks" / f"00_stage_data_{shard}.ipynb"


NOTEBOOK = path(1)

INTRO = """# Stage KiTS23 v0.1.4 on Kaggle — shard {shard} of {n} (CPU, no GPU quota)

Downloads about 14 GB of the pinned KiTS23 files straight from HuggingFace into
this notebook's output, checking every file's size and SHA-256 against the
project manifest.{segs} Kaggle keeps at most about 20 GB of output, so the data is
split over {n} notebooks.

*Settings*: **Accelerator = None**, **Internet = On**, keep the notebook **Private**
(the data license is CC BY-NC-SA 4.0). Then **Save Version → Save & Run All**.
Notebooks 01 and 03 take the outputs of all {n} shards as input.

Generated by `scripts/data/build_stage_notebook.py`; edit the repository, not this notebook."""

SETUP = """import os, sys, subprocess
for sub in ("scripts/data", "data/sources"):
    os.makedirs(f"/kaggle/working/project23d/{sub}", exist_ok=True)"""

RUN = """SHARD = {shard}
W = "/kaggle/working/project23d"
subprocess.run([sys.executable, f"{{W}}/scripts/data/stage_kits23.py",
                "--manifest", f"{{W}}/data/sources/kits23_v0.1.4_files.tsv",
                "--shard", str(SHARD), "--n-shards", "{n}",
                "--out-dir", "/kaggle/working/kits23"], check=True)"""


def build(shard: int = 1) -> dict:
    segs = " This shard also holds all 489 segmentations." if shard == 1 else ""
    return notebook([md_cell(INTRO.format(shard=shard, n=N_SHARDS, segs=segs)), code_cell(SETUP),
                     *writefile_cells(EMBEDDED), code_cell(RUN.format(shard=shard, n=N_SHARDS))])


def render(shard: int = 1) -> str:
    return json.dumps(build(shard), indent=1, ensure_ascii=False) + "\n"


if __name__ == "__main__":
    for k in range(1, N_SHARDS + 1):
        path(k).parent.mkdir(parents=True, exist_ok=True)
        path(k).write_text(render(k), encoding="utf-8", newline="\n")
        print(f"wrote {path(k)}")
